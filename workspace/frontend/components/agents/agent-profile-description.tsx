'use client';

import { useCallback, useEffect, useState } from 'react';
import { Sparkles } from 'lucide-react';
import { toast } from 'sonner';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader } from '@/components/ui/card';
import { Spinner } from '@/components/ui/spinner';
import { Textarea } from '@/components/ui/textarea';
import { workspaceApi } from '@/lib/api';
import { useT } from '@/lib/i18n';
import type { WorkspaceAgent } from '@/lib/types';

/** What the agent is for — a local draft saved on blur, or suggested by the server. */
export function AgentDescriptionCard({ agent, canManage, refreshWorkspace }: { agent: WorkspaceAgent; canManage: boolean; refreshWorkspace: () => Promise<void> }) {
  const t = useT();
  const [description, setDescription] = useState('');
  const [saving, setSaving] = useState(false);
  const [descDirty, setDescDirty] = useState(false);
  const [generatingDesc, setGeneratingDesc] = useState(false);

  // Sync description when agent changes
  useEffect(() => {
    setDescription(agent.description || '');
    setDescDirty(false);
  }, [agent.agentName, agent.description]);

  const handleSaveDescription = useCallback(async () => {
    if (!descDirty) return;
    setSaving(true);
    try {
      await workspaceApi.updateMember(agent.agentName, { description });
      await refreshWorkspace();
      setDescDirty(false);
      toast.success(t('agents.descriptionSaved'));
    } catch {
      toast.error(t('agents.descriptionSaveFailed'));
    } finally {
      setSaving(false);
    }
  }, [agent, description, descDirty, refreshWorkspace]);

  const handleGenerateDescription = useCallback(async () => {
    setGeneratingDesc(true);
    try {
      const suggestion = await workspaceApi.generateMemberDescription(agent.agentName);
      if (suggestion) {
        setDescription(suggestion);
        setDescDirty(true);
        toast.success(t('agents.autoGenerated'));
      } else {
        toast.error(t('agents.autoGenerateEmpty'));
      }
    } catch {
      toast.error(t('agents.autoGenerateFailed'));
    } finally {
      setGeneratingDesc(false);
    }
  }, [agent]);

  return (
    <Card size="sm" className="gap-0 overflow-visible rounded-none border-b bg-transparent py-5 ring-0">
      <CardHeader className="flex items-center justify-between gap-2 px-0 pb-3 pt-0">
        <span className="text-sm font-medium">{t('agents.description')}</span>
        {canManage && (
          <Button
            variant="ghost"
            size="xs"
            onClick={handleGenerateDescription}
            disabled={generatingDesc}
            className="shrink-0 text-muted-foreground"
            title={t('agents.autoGenerateHint')}
          >
            {generatingDesc
              ? <Spinner data-icon="inline-start" />
              : <Sparkles data-icon="inline-start" className="text-warning" />}
            {generatingDesc ? t('agents.generating') : t('agents.autoGenerate')}
          </Button>
        )}
      </CardHeader>
      <CardContent className="flex flex-col gap-2 px-0 py-0">
        <Textarea
          className="min-h-24 resize-y bg-muted/20 text-sm leading-relaxed"
          placeholder={t('agents.descriptionPlaceholder', { agent: agent.agentName })}
          value={description}
          onChange={(e) => {
            setDescription(e.target.value);
            setDescDirty(true);
          }}
          onBlur={canManage ? handleSaveDescription : undefined}
          readOnly={!canManage}
          rows={3}
        />
        <p className="text-xs leading-relaxed text-muted-foreground">{t(canManage ? 'agents.descriptionScope' : 'agents.ownerOnlyHint')}</p>
        {descDirty && (
          <div className="flex justify-end">
            <Button size="xs" onClick={handleSaveDescription} disabled={saving}>
              {saving ? t('common.saving') : t('common.save')}
            </Button>
          </div>
        )}
      </CardContent>
    </Card>
  );
}
